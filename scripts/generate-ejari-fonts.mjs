import { Font, Encodings } from '@pdf-lib/standard-fonts'
import { readFileSync, writeFileSync } from 'node:fs'

// Generate only the Helvetica metrics needed by EJARI, without importing a PDF
// document engine into the browser. Source package/data distributed under MIT.
const font = Font.load('Helvetica')
const entries = Encodings.WinAnsi.supportedCodePoints.map(cp => [cp, Encodings.WinAnsi.encodeUnicodeCodePoint(cp)])
const encoding = Object.fromEntries(entries.map(([cp, glyph]) => [cp, glyph.code]))
const widths = Object.fromEntries(entries.map(([, glyph]) => [glyph.code, font.getWidthOfGlyph(glyph.name) ?? 250]))
const kerning = {}
for (const [, left] of entries) for (const [, right] of entries) {
  const value = font.getXAxisKerningForPair(left.name, right.name)
  if (value) kerning[left.code * 256 + right.code] = value
}
writeFileSync(new URL('../app/utils/ejari-fonts.ts', import.meta.url),
  '// Generated by scripts/generate-ejari-fonts.mjs from @pdf-lib/standard-fonts 1.0.0.\n' +
  '/*\n' + readFileSync(new URL('../node_modules/@pdf-lib/standard-fonts/LICENSE.md',import.meta.url),'utf8') + '\n*/\n' +
  Object.entries({ encoding, widths, kerning }).map(([name, data]) => `export const ${name}: Record<number, number> = ${JSON.stringify(data)}\n`).join(''))
